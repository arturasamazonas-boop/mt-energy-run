export function detectLang() {
  const saved = prefs.get('lang');
  if (saved === 'lt' || saved === 'en') return saved;
  const nav = (navigator.languages || [navigator.language || 'lt']).join(',').toLowerCase();
  return /(^|,)lt\b/.test(nav) ? 'lt' : 'en';
}

let lang = detectLang();

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'lt';
  prefs.set('lang', lang);
  document.documentElement.lang = lang;
}

export function t(key) {
  return STR[lang][key] ?? STR.lt[key] ?? key;
}

/** Pick lt/en from an object like { lt, en } or { lt: 'x', en: 'y', descLt, descEn }. */
export function L(obj, base = '') {
  if (!obj) return '';
  if (base) return obj[base + (lang === 'lt' ? 'Lt' : 'En')];
  return obj[lang] ?? obj.lt;
}

export function fmtNum(n) {
  return Math.floor(n).toLocaleString(lang === 'lt' ? 'lt-LT' : 'en-GB');
}

export function fmtDist(m) {
  if (m >= 1000) return `${(m / 1000).toFixed(m >= 10000 ? 1 : 2).replace('.', lang === 'lt' ? ',' : '.')} ${t('km')}`;
  return `${Math.floor(m)} ${t('m')}`;
}
